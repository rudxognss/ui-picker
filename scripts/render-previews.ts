// Renders every finished scene to 40 indexed PNG frames and writes hooks/previews/png-frames.ts.
// Run: bun scripts/render-previews.ts [--check] [--only id,id --out dir]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { SLOTS } from '../hooks/previews/canvas'
import { renderSlot, sceneHash } from '../hooks/previews/pixel'
import { SCENES } from '../hooks/previews/scenes/index'
import { encodeIndexedPng } from './png'

const PNG_W = 480
const PNG_H = 320
const HOLD_SLOT = 20
const FRAME_MAX = 4_000
const ID_MAX = 30_000
const MODULE_MAX = 600_000
const MODULE_TARGET = 350_000
const OUT_FILE = decodeURIComponent(new URL('../hooks/previews/png-frames.ts', import.meta.url).pathname)
const HEADER = '// Generated by scripts/render-previews.ts (do not edit). Run: bun scripts/render-previews.ts [--check] [--only id,id --out dir]'

type Row = { id: string; unique: number; bytes: number; depths: string }

function parseArgs(argv: string[]): { check: boolean; only?: string[]; out?: string } {
  const a: { check: boolean; only?: string[]; out?: string } = { check: false }
  for (let i = 0; i < argv.length; i++) {
    const v = argv[i]
    if (v === '--check') a.check = true
    else if (v === '--only') a.only = (argv[++i] ?? '').split(',').filter(Boolean)
    else if (v === '--out') a.out = argv[++i]
    else throw new Error('unknown argument: ' + v)
  }
  if ((a.only === undefined) !== (a.out === undefined)) throw new Error('--only and --out go together')
  return a
}

const fail = (msg: string): never => {
  console.error('render-previews: ' + msg)
  process.exit(1)
}

const args = parseArgs(process.argv.slice(2))
const all = Object.keys(SCENES).filter(id => id !== 'window')
const ids = args.only ?? all
for (const id of ids) if (!all.includes(id)) fail('no scene for id "' + id + '"')

if (args.out !== undefined) {
  mkdirSync(args.out, { recursive: true })
  for (const id of ids)
    for (let s = 0; s < SLOTS; s++) {
      const c = renderSlot(SCENES[id]!, PNG_W, PNG_H, s)
      const { png } = encodeIndexedPng({ W: c.W, H: c.H, idx: c.idx, palette: c.palette })
      writeFileSync(args.out + '/' + id + '-' + String(s).padStart(2, '0') + '.png', png)
    }
  console.log('wrote ' + ids.length * SLOTS + ' frames to ' + args.out)
  process.exit(0)
}

const pool: string[] = []
const poolIndex = new Map<string, number>()
const index: Record<string, number[]> = {}
const hashes: Record<string, string> = {}
const rows: Row[] = []

for (const id of ids) {
  const slots: number[] = []
  const depths = new Set<number>()
  const seen = new Set<number>()
  let bytes = 0
  for (let s = 0; s < SLOTS; s++) {
    const c = renderSlot(SCENES[id]!, PNG_W, PNG_H, s)
    const { png, bitDepth } = encodeIndexedPng({ W: c.W, H: c.H, idx: c.idx, palette: c.palette })
    const b64 = Buffer.from(png).toString('base64')
    if (b64.length > FRAME_MAX) fail(id + ' slot ' + s + ': frame ' + b64.length + ' B > ' + FRAME_MAX)
    let i = poolIndex.get(b64)
    if (i === undefined) {
      i = pool.length
      pool.push(b64)
      poolIndex.set(b64, i)
    }
    slots.push(i)
    depths.add(bitDepth)
    if (!seen.has(i)) {
      seen.add(i)
      bytes += b64.length
    }
  }
  if (slots[0] === slots[HOLD_SLOT]) fail(id + ': slot 0 and slot ' + HOLD_SLOT + ' render the same frame')
  if (bytes > ID_MAX) fail(id + ': ' + bytes + ' B > ' + ID_MAX)
  index[id] = slots
  hashes[id] = sceneHash(SCENES[id]!, PNG_W, PNG_H)
  rows.push({ id, unique: seen.size, bytes, depths: [...depths].sort().join('/') })
}

const q = (s: string): string => "'" + s + "'"
const module =
  HEADER +
  '\n' +
  `export const PNG_W = ${PNG_W}, PNG_H = ${PNG_H}, SLOTS = ${SLOTS}\n` +
  'export const PNG_UNIQUE: readonly string[] = [\n' +
  pool.map(f => '  ' + q(f) + ',\n').join('') +
  ']\n' +
  'export const PNG_INDEX: Readonly<Record<string, readonly number[]>> = {\n' +
  ids.map(id => '  ' + q(id) + ': [' + index[id]!.join(', ') + '],\n').join('') +
  '}\n' +
  'export const SCENE_HASH: Readonly<Record<string, string>> = {\n' +
  ids.map(id => '  ' + q(id) + ': ' + q(hashes[id]!) + ',\n').join('') +
  '}\n'

if (module.length > MODULE_MAX) fail('module ' + module.length + ' B > ' + MODULE_MAX)

const pad = (s: string | number, n: number): string => String(s).padStart(n)
console.log(pad('id', 20) + pad('unique', 8) + pad('bytes', 9) + pad('depth', 7))
for (const r of rows) console.log(pad(r.id, 20) + pad(r.unique, 8) + pad(r.bytes, 9) + pad(r.depths, 7))
const total = rows.reduce((n, r) => n + r.bytes, 0)
console.log(pad('pool', 20) + pad(pool.length, 8) + pad(pool.reduce((n, f) => n + f.length, 0), 9))
console.log(`module ${module.length} B (target ${MODULE_TARGET}, max ${MODULE_MAX}); per-id mean ${Math.round(total / rows.length)} B; 25 ids projected ~${Math.round((total / rows.length) * 25)} B`)

if (args.check) {
  let current = ''
  try {
    current = readFileSync(OUT_FILE, 'utf8')
  } catch {
    fail('png-frames.ts is missing; run without --check')
  }
  if (current === module) {
    console.log('png-frames.ts is up to date')
    process.exit(0)
  }
  const cur = /PNG_INDEX[^{]*\{([\s\S]*?)\n\}/.exec(current)?.[1] ?? ''
  const curIds = [...cur.matchAll(/'([^']+)':/g)].map(m => m[1]!)
  fail(`png-frames.ts is stale (${current.length} B on disk, ${module.length} B rendered; ids on disk ${curIds.length}, rendered ${ids.length}). Run: bun scripts/render-previews.ts`)
}

writeFileSync(OUT_FILE, module)
console.log('wrote ' + OUT_FILE)
