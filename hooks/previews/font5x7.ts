const FONT_FIRST = 32
const FONT_LAST = 126
export const GLYPH_W = 5
export const GLYPH_H = 7
/** Horizontal advance per character: glyph width plus one dot of spacing. */
export const ADVANCE = GLYPH_W + 1

/** 95 glyphs x 7 row bytes; row byte bit (4 - col) is dot `col`. */
export const FONT: Uint8Array = new Uint8Array(GLYPHS.length * GLYPH_H)
GLYPHS.forEach((g, i) => {
  const rows = g.split(' ')
  if (rows.length !== GLYPH_H || rows.some(r => r.length !== GLYPH_W)) throw new Error('font5x7: bad glyph ' + (i + FONT_FIRST))
  rows.forEach((r, y) => {
    let b = 0
    for (let x = 0; x < GLYPH_W; x++) if (r[x] === '#') b |= 1 << (GLYPH_W - 1 - x)
    FONT[i * GLYPH_H + y] = b
  })
})

/** Non-ASCII code points drawn with an ASCII look-alike. */
const ALIASES: Readonly<Record<number, number>> = { 0xd7: 0x78 /* × -> x */ }

/** Row byte `row` of the glyph for `code`, or 0 when the font has no glyph for it. */
export function glyphRow(code: number, row: number): number {
  const c = ALIASES[code] ?? code
  if (c < FONT_FIRST || c > FONT_LAST) return 0
  return FONT[(c - FONT_FIRST) * GLYPH_H + row] ?? 0
}

/** Width in design units of `s` at `scale`, spacing after the last glyph excluded. */
export function textWidth(s: string, scale = 1): number {
  return s.length === 0 ? 0 : (s.length * ADVANCE - 1) * scale
}
